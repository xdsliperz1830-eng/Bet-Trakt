#!/usr/bin/env node
/*
 * Copy the web app into www/, the folder Capacitor packages into the
 * Android and iPhone apps. Run before `npx cap sync`.
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const out = path.join(root, 'www');
const FILES = ['index.html', 'styles.css', 'sw.js', 'manifest.webmanifest', 'js', 'icons'];

fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(out, { recursive: true });
for (const f of FILES) fs.cpSync(path.join(root, f), path.join(out, f), { recursive: true });

// The native apps need Capacitor's core script for plugins (sharing files, etc.).
fs.copyFileSync(path.join(root, 'node_modules/@capacitor/core/dist/capacitor.js'), path.join(out, 'js/capacitor.js'));
const indexPath = path.join(out, 'index.html');
const html = fs.readFileSync(indexPath, 'utf8');
if (!html.includes('<script src="js/calc.js"></script>')) throw new Error('index.html: calc.js script tag not found');
fs.writeFileSync(indexPath, html.replace('<script src="js/calc.js"></script>', '<script src="js/capacitor.js"></script>\n  <script src="js/calc.js"></script>'));
fs.writeFileSync(path.join(out, 'js/build-info.js'),
  '/* Generated by scripts/build-web.js */\nwindow.BETTRAKT_BUILD = ' + JSON.stringify(Number(process.env.BUILD_NUMBER) || 0) + ';\n');
fs.writeFileSync(indexPath, fs.readFileSync(indexPath, 'utf8').replace('<script src="js/capacitor.js"></script>', '<script src="js/capacitor.js"></script>\n  <script src="js/build-info.js"></script>'));
console.log('Copied ' + FILES.join(', ') + ' and Capacitor core to www/ (build ' + (Number(process.env.BUILD_NUMBER) || 0) + ')');
